create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  phone text,
  age integer,
  city text,
  avatar_url text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.trips (
  id text primary key,
  name text not null,
  short text,
  status text not null default 'wishlist' check (status in ('completed','upcoming','ongoing','wishlist','cancelled')),
  start_date date,
  end_date date,
  place text,
  country text not null default 'India',
  state text,
  latitude double precision,
  longitude double precision,
  summary text,
  experience text,
  budget numeric(12,2) not null default 0,
  capacity integer not null default 1 check (capacity > 0),
  icon text,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.trip_members (
  id bigint generated by default as identity primary key,
  trip_id text not null references public.trips(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null,
  member_name text not null,
  is_verified boolean not null default false,
  joined_at timestamptz not null default now(),
  unique (trip_id, user_id),
  unique (trip_id, member_name)
);

create table if not exists public.trip_applications (
  id bigint generated by default as identity primary key,
  trip_id text not null references public.trips(id) on delete cascade,
  applicant_id uuid references public.profiles(id) on delete set null,
  name text not null,
  phone text not null,
  age integer,
  city text,
  message text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references public.profiles(id) on delete set null
);

create table if not exists public.itinerary_days (
  id bigint generated by default as identity primary key,
  trip_id text not null references public.trips(id) on delete cascade,
  day_number integer not null,
  title text not null,
  description text,
  unique (trip_id, day_number)
);

create table if not exists public.itinerary_activities (
  id bigint generated by default as identity primary key,
  itinerary_day_id bigint not null references public.itinerary_days(id) on delete cascade,
  sort_order integer not null default 0,
  title text not null,
  description text,
  start_time time
);

create table if not exists public.memories (
  id bigint generated by default as identity primary key,
  trip_id text references public.trips(id) on delete set null,
  author_id uuid references public.profiles(id) on delete set null,
  author_name text not null,
  title text not null,
  body text not null,
  status text not null default 'approved' check (status in ('pending','approved','rejected')),
  wall_x double precision not null default 0,
  wall_y double precision not null default 0,
  rotation double precision not null default 0,
  scale double precision not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.media (
  id bigint generated by default as identity primary key,
  trip_id text references public.trips(id) on delete set null,
  type text not null default 'photo' check (type in ('photo','video')),
  title text not null,
  url text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.site_requests (
  id bigint generated by default as identity primary key,
  type text not null,
  trip_id text references public.trips(id) on delete set null,
  name text not null,
  destination text,
  date date,
  people integer,
  phone text,
  age integer,
  city text,
  message text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references public.profiles(id) on delete set null
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  body text not null,
  type text not null default 'info',
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name',
             new.raw_user_meta_data ->> 'name',
             split_part(coalesce(new.email,''), '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

