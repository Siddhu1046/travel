drop policy if exists "public read trips" on public.trips;
create policy "public read trips" on public.trips for select using (true);
drop policy if exists "admins manage trips" on public.trips;
create policy "admins manage trips" on public.trips for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "users read profiles" on public.profiles;
create policy "users read profiles" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
